﻿# coding: utf-8 powershell
# 一键把 rxlib 平台配置为“登录后自动后台运行”，无需管理员权限。
# 原理：在当前用户的“启动文件夹”放置一个静默启动器（.vbs），
# 登录时由系统调用 pythonw.exe 运行 launcher.py：
#   - 无黑窗口
#   - 输出写入 logs\launcher-*.log
# 卸载请运行 uninstall-task.ps1
param(
    [int]$Port = 8504
)

$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $MyInvocation.MyCommand.Path
$AppDir = Join-Path $Root 'app\current'
$ManifestPath = Join-Path $AppDir 'manifest.json'
$Launcher = Join-Path $Root 'launcher.py'
$ShortcutName = 'rxlib_wyckoff-platform'

if (-not (Test-Path $ManifestPath)) { Write-Host "未找到版本清单：$ManifestPath" -ForegroundColor Red; exit 1 }
if (-not (Test-Path $Launcher)) { Write-Host "未找到启动器：$Launcher" -ForegroundColor Red; exit 1 }

$manifest = Get-Content $ManifestPath -Raw -Encoding UTF8 | ConvertFrom-Json
$runtimeName = if ($manifest.runtime) { $manifest.runtime } else { 'python310' }
$PythonW = Join-Path $Root (Join-Path "runtime\$runtimeName" 'pythonw.exe')

# 首次运行若缺少便携运行时，自动下载（复用 run.ps1 同一引导脚本）
if (-not (Test-Path $PythonW)) {
    & (Join-Path $Root 'bootstrap_runtime.ps1') -Root $Root
    if ($LASTEXITCODE -ne 0) {
        Write-Host "未找到无窗口运行时：$PythonW" -ForegroundColor Red
        Read-Host '按回车退出'
        exit 1
    }
}

if (-not (Test-Path $PythonW)) { Write-Host "未找到无窗口运行时：$PythonW" -ForegroundColor Red; Read-Host '按回车退出'; exit 1 }

# 端口已被占用时不重复启动
function Test-PortOpen([int]$TargetPort) {
    $client = New-Object System.Net.Sockets.TcpClient
    try {
        $async = $client.BeginConnect('127.0.0.1', $TargetPort, $null, $null)
        if ($async.AsyncWaitHandle.WaitOne(800)) { $client.EndConnect($async); return $true }
        return $false
    } catch { return $false } finally { $client.Close() }
}

if (Test-PortOpen $Port) {
    Write-Host "端口 $Port 已有服务在运行；如要重装请先执行 uninstall-task.ps1。" -ForegroundColor Yellow
    exit 0
}

# 在启动文件夹生成 VBS：通过环境变量 RXLIB_PORT 传端口，静默调用 pythonw。
# WScript.Shell 运行方式默认不弹窗。
$StartupDir = [Environment]::GetFolderPath('Startup')
if (-not (Test-Path $StartupDir)) { New-Item -ItemType Directory -Path $StartupDir | Out-Null }
$VbsPath = Join-Path $StartupDir ("{0}.vbs" -f $ShortcutName)

$vbs = @"
' rxlib silent launcher (generated by install-task.ps1; delete this file to disable)
Set sh = CreateObject("WScript.Shell")
Set env = sh.Environment("PROCESS")
env("RXLIB_PORT") = "$Port"
sh.CurrentDirectory = "$Root"
sh.Run """$PythonW"" ""$Launcher""", 0, False
"@
[System.IO.File]::WriteAllText($VbsPath, $vbs, (New-Object System.Text.ASCIIEncoding))

Write-Host '已写入启动项，正在立即启动...' -ForegroundColor Cyan
Start-Process -FilePath 'wscript.exe' -ArgumentList ("`"{0}`"" -f $VbsPath) -WindowStyle Hidden

# 等待端口就绪以确认启动成功
$ok = $false
for ($i = 1; $i -le 30; $i++) {
    Start-Sleep -Seconds 1
    if (Test-PortOpen $Port) { $ok = $true; break }
}

if ($ok) {
    Write-Host ''
    Write-Host '配置成功，平台已在后台运行。' -ForegroundColor Green
    Write-Host ("  访问地址：http://localhost:{0}" -f $Port)
    Write-Host ("  日志目录：{0}\logs" -f $Root)
    Write-Host "  登录 Windows 后将自动静默启动。"
    Write-Host "  停用请运行：uninstall-task.ps1"
    Start-Process ("http://localhost:{0}" -f $Port)
} else {
    Write-Host "启动项已配置，但 $Port 端口暂未就绪，请查看 logs\launcher-*.log" -ForegroundColor Yellow
    exit 1
}
